  app.post(
    '/api/schools/:schoolId/goods-receipts',
    { preHandler: requirePermission('procurement.request') },
    idempotentRoute('POST /goods-receipts', async (request, reply) => {
      const { schoolId } = parseInput(schoolParams, request.params);
      const input = parseInput(goodsReceiptInput, request.body);
      const actor = getActor(request);
      const receiptId = await withTransaction(async (client) => {
        const order = await client.query<{ status: PurchaseOrder['status'] }>(
          'SELECT status FROM purchase_orders WHERE school_id = $1 AND id = $2 FOR UPDATE',
          [schoolId, input.poId],
        );
        const status = order.rows[0]?.status;
        if (!status) throw notFound('Purchase order not found');
        if (!['issued', 'partially_received'].includes(status)) {
          throw conflict('Goods can only be received against an issued order');
        }
        const { rows } = await client.query<{ id: string }>(
          `INSERT INTO goods_receipts (school_id, po_id, received_on, received_by, notes)
           VALUES ($1, $2, COALESCE($3::date, current_date), $4, $5) RETURNING id`,
          [schoolId, input.poId, input.receivedOn ?? null, actor.userId, input.notes ?? null],
        );
        const receipt = rows[0]!.id;
        for (const item of input.items) {
          const poItem = await client.query<{ quantity: string; received_quantity: string }>(
            `SELECT quantity, received_quantity FROM purchase_order_items
             WHERE school_id = $1 AND id = $2 AND po_id = $3 FOR UPDATE`,
            [schoolId, item.poItemId, input.poId],
          );
          const row = poItem.rows[0];
          if (!row) throw notFound('Order line not found on this purchase order');
          const remaining = toNumber(row.quantity) - toNumber(row.received_quantity);
          if (item.quantity > remaining + 0.0001) {
            throw badRequest('A receipt exceeds the outstanding quantity for an order line');
          }
          await client.query(
            `INSERT INTO goods_receipt_items
               (school_id, receipt_id, po_item_id, quantity, discrepancy_note)
             VALUES ($1, $2, $3, $4, $5)`,
            [schoolId, receipt, item.poItemId, item.quantity, item.discrepancyNote ?? null],
          );
          await client.query(
            `UPDATE purchase_order_items SET received_quantity = received_quantity + $3
             WHERE school_id = $1 AND id = $2`,
            [schoolId, item.poItemId, item.quantity],
          );
        }
        const outstanding = await client.query<{ remaining: string }>(
          `SELECT COALESCE(sum(quantity - received_quantity), 0)::text AS remaining
           FROM purchase_order_items WHERE school_id = $1 AND po_id = $2`,
          [schoolId, input.poId],
        );
        await client.query(
          `UPDATE purchase_orders SET status = $3 WHERE school_id = $1 AND id = $2`,
          [
            schoolId,
            input.poId,
            toNumber(outstanding.rows[0]?.remaining) <= 0 ? 'received' : 'partially_received',
          ],
        );
        await recordAudit(client, {
          schoolId,
          actorUserId: actor.userId,
          action: 'procurement.goods_received',
          entityType: 'goods_receipt',
          entityId: receipt,
          outcome: 'success',
          after: { poId: input.poId, lines: input.items.length },
          ...requestMeta(request),
        });
        return receipt;
      });
      return reply.status(201).send({ id: receiptId });
    }),
  );

