/* --------------------------------- helpers -------------------------------- */

async function nextCode(
  table: string,
  prefix: string,
  schoolId: string,
): Promise<string> {
  return nextCodeIn(getPool(), table, prefix, schoolId);
}

async function nextCodeIn(
  client: Pick<pg.Pool, 'query'>,
  table: string,
  prefix: string,
  schoolId: string,
): Promise<string> {
  const { rows } = await client.query<{ count: string }>(
    `SELECT count(*)::text AS count FROM ${table} WHERE school_id = $1`,
    [schoolId],
  );
  return `${prefix}-${String(Number(rows[0]?.count ?? 0) + 1).padStart(4, '0')}`;
}
