export type ScopeType =
  | 'school'
  | 'campus'
  | 'department'
  | 'class'
  | 'section'
  | 'self'
  | 'linked_student'
  | 'custom';

export interface RoleDefinition {
  code: string;
  name: string;
  description: string;
  defaultScopeType: ScopeType;
  permissions: Permission[];
}

